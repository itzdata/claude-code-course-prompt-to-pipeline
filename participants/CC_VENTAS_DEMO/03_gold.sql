-- Gold de VENTAS_DEMO | INI = CC
USE ROLE COFFEE_LAB_PARTICIPANT;
USE WAREHOUSE COMPUTE_WH;

CREATE SCHEMA IF NOT EXISTS COFFEE_GOLD.CC_VENTAS_DEMO
  COMMENT = 'Gold de VENTAS_DEMO | owner: Claude Code | fuente: VENTAS_DEMO';

CREATE OR REPLACE DYNAMIC TABLE COFFEE_GOLD.CC_VENTAS_DEMO.AGG_SALES_DAILY_STORE
  TARGET_LAG = '1 day' WAREHOUSE = COMPUTE_WH
  COMMENT = 'Ventas diarias por tienda y categoría | owner: Claude Code | fuente: VENTAS_DEMO'
AS
SELECT F.ORDER_DATE, S.STORE_NAME, S.CITY_NAME, P.CATEGORY_NAME,
       COUNT(DISTINCT F.ORDER_ID) AS ORDER_CNT, SUM(F.ITEM_QTY) AS ITEM_QTY, SUM(F.TOTAL_AMT) AS TOTAL_AMT,
       SUM(F.TOTAL_AMT) / NULLIF(COUNT(DISTINCT F.ORDER_ID), 0) AS AVG_TICKET_AMT
FROM COFFEE_SILVER.CC_VENTAS_DEMO.FCT_SALES F
JOIN COFFEE_SILVER.CC_VENTAS_DEMO.DIM_PRODUCT P ON P.PRODUCT_SK = F.PRODUCT_SK
JOIN COFFEE_SILVER.CC_VENTAS_DEMO.DIM_STORE S ON S.STORE_SK = F.STORE_SK
GROUP BY ALL;

CREATE OR REPLACE VIEW COFFEE_GOLD.CC_VENTAS_DEMO.KPI_SALES
  COMMENT = 'KPIs de ventas por mes | owner: Claude Code | fuente: VENTAS_DEMO'
AS
WITH M AS (
  SELECT DATE_TRUNC(MONTH, ORDER_DATE) AS MONTH_DATE, SUM(TOTAL_AMT) AS TOTAL_AMT, SUM(ORDER_CNT) AS ORDER_CNT
  FROM COFFEE_GOLD.CC_VENTAS_DEMO.AGG_SALES_DAILY_STORE GROUP BY 1)
SELECT MONTH_DATE, TOTAL_AMT, ORDER_CNT, TOTAL_AMT / NULLIF(ORDER_CNT, 0) AS AVG_TICKET_AMT,
       TOTAL_AMT / NULLIF(LAG(TOTAL_AMT) OVER (ORDER BY MONTH_DATE), 0) - 1 AS GROWTH_PCT
FROM M;

CREATE OR REPLACE SEMANTIC VIEW COFFEE_GOLD.CC_VENTAS_DEMO.SV_VENTAS_DEMO
  TABLES (
    SALES    AS COFFEE_SILVER.CC_VENTAS_DEMO.FCT_SALES PRIMARY KEY (ORDER_ID, PRODUCT_SK) COMMENT = 'Líneas de venta',
    PRODUCTS AS COFFEE_SILVER.CC_VENTAS_DEMO.DIM_PRODUCT PRIMARY KEY (PRODUCT_SK) WITH SYNONYMS = ('artículos','products') COMMENT = 'Productos',
    STORES   AS COFFEE_SILVER.CC_VENTAS_DEMO.DIM_STORE PRIMARY KEY (STORE_SK) WITH SYNONYMS = ('tiendas','sucursales','stores') COMMENT = 'Tiendas'
  )
  RELATIONSHIPS (
    SALES_TO_PRODUCT AS SALES (PRODUCT_SK) REFERENCES PRODUCTS,
    SALES_TO_STORE   AS SALES (STORE_SK) REFERENCES STORES
  )
  DIMENSIONS (
    SALES.ORDER_DATE AS ORDER_DATE WITH SYNONYMS = ('fecha','date') COMMENT = 'Fecha de la orden',
    SALES.PAYMENT_METHOD_NAME AS PAYMENT_METHOD_NAME WITH SYNONYMS = ('método de pago','payment') COMMENT = 'Método de pago',
    PRODUCTS.PRODUCT_NAME AS PRODUCT_NAME WITH SYNONYMS = ('producto','product'),
    PRODUCTS.CATEGORY_NAME AS CATEGORY_NAME WITH SYNONYMS = ('categoría','category'),
    STORES.STORE_NAME AS STORE_NAME WITH SYNONYMS = ('tienda','sucursal','store'),
    STORES.CITY_NAME AS CITY_NAME WITH SYNONYMS = ('ciudad','city')
  )
  METRICS (
    SALES.TOTAL_SALES AS SUM(TOTAL_AMT) WITH SYNONYMS = ('ventas','ingresos','revenue') COMMENT = 'Ventas totales en USD',
    SALES.ORDERS      AS COUNT(DISTINCT ORDER_ID) WITH SYNONYMS = ('órdenes','pedidos','orders') COMMENT = 'Número de órdenes',
    SALES.UNITS       AS SUM(ITEM_QTY) WITH SYNONYMS = ('unidades','units') COMMENT = 'Unidades vendidas'
  )
  COMMENT = 'Semantic view de VENTAS_DEMO | owner: Claude Code | fuente: VENTAS_DEMO';

-- Validaciones: la semantic view responde y AGG cuadra con FCT
SELECT * FROM SEMANTIC_VIEW(COFFEE_GOLD.CC_VENTAS_DEMO.SV_VENTAS_DEMO DIMENSIONS PRODUCTS.CATEGORY_NAME METRICS SALES.TOTAL_SALES) ORDER BY TOTAL_SALES DESC;
SELECT (SELECT SUM(TOTAL_AMT) FROM COFFEE_SILVER.CC_VENTAS_DEMO.FCT_SALES)
     - (SELECT SUM(TOTAL_AMT) FROM COFFEE_GOLD.CC_VENTAS_DEMO.AGG_SALES_DAILY_STORE) AS DIFERENCIA_DEBE_SER_0;
