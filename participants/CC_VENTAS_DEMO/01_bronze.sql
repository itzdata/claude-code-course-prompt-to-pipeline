-- Prueba del repo: el CSV vive en un stage propio del participante (el stage compartido LANDING es solo lectura).
USE ROLE COFFEE_LAB_PARTICIPANT;
USE WAREHOUSE COMPUTE_WH;

CREATE SCHEMA IF NOT EXISTS COFFEE_BRONZE.CC_VENTAS_DEMO
  COMMENT = 'Bronze de VENTAS_DEMO | owner: Claude Code | fuente: VENTAS_DEMO';

CREATE STAGE IF NOT EXISTS COFFEE_BRONZE.CC_VENTAS_DEMO.STG_DEMO
  COMMENT = 'Stage de prueba con ventas_demo.csv | owner: Claude Code | fuente: VENTAS_DEMO';
-- Carga del archivo (una vez):  PUT file://datasets/demo/ventas_demo.csv @COFFEE_BRONZE.CC_VENTAS_DEMO.STG_DEMO AUTO_COMPRESS=FALSE OVERWRITE=TRUE;

-- Copia fiel: todo VARCHAR (el archivo trae fechas y precios inválidos a propósito)
CREATE OR REPLACE TABLE COFFEE_BRONZE.CC_VENTAS_DEMO.RAW_ORDERS (
  ORDER_ID VARCHAR, ORDER_DATE VARCHAR, STORE_ID VARCHAR, STORE_NAME VARCHAR, CITY VARCHAR, PRODUCT_ID VARCHAR,
  PRODUCT_NAME VARCHAR, CATEGORY VARCHAR, QUANTITY VARCHAR, UNIT_PRICE VARCHAR, DISCOUNT_PCT VARCHAR, PAYMENT_METHOD VARCHAR,
  _FILE_NAME VARCHAR, _FILE_ROW NUMBER, _LOADED_TS TIMESTAMP_LTZ
) COMMENT = 'Carga cruda de ventas_demo.csv | owner: Claude Code | fuente: VENTAS_DEMO';

COPY INTO COFFEE_BRONZE.CC_VENTAS_DEMO.RAW_ORDERS
  FROM @COFFEE_BRONZE.CC_VENTAS_DEMO.STG_DEMO/ventas_demo.csv
  FILE_FORMAT = (FORMAT_NAME = 'COFFEE_BRONZE.LANDING.FF_CSV')
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
  INCLUDE_METADATA = (_FILE_NAME = METADATA$FILENAME, _FILE_ROW = METADATA$FILE_ROW_NUMBER, _LOADED_TS = METADATA$START_SCAN_TIME)
  ON_ERROR = CONTINUE;

SELECT 'RAW_ORDERS' AS TABLA, COUNT(*) AS FILAS, COUNT(DISTINCT _FILE_NAME) AS ARCHIVOS FROM COFFEE_BRONZE.CC_VENTAS_DEMO.RAW_ORDERS;
