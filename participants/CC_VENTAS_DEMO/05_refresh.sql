-- Procedimiento ÚNICO de reproceso de VENTAS_DEMO | INI = CC
USE ROLE COFFEE_LAB_PARTICIPANT;
USE WAREHOUSE COMPUTE_WH;

CREATE OR REPLACE PROCEDURE COFFEE_GOLD.CC_VENTAS_DEMO.SP_REFRESH_VENTAS_DEMO()
  RETURNS VARCHAR
  LANGUAGE SQL
  COMMENT = 'Reproceso total Bronze->Silver->Gold | owner: Claude Code | fuente: VENTAS_DEMO'
  EXECUTE AS CALLER
AS
$$
DECLARE
  resumen VARCHAR DEFAULT '';
  n NUMBER;
BEGIN
  -- 1. Bronze: vaciar y recargar sin duplicar
  TRUNCATE TABLE COFFEE_BRONZE.CC_VENTAS_DEMO.RAW_ORDERS;
  COPY INTO COFFEE_BRONZE.CC_VENTAS_DEMO.RAW_ORDERS
    FROM @COFFEE_BRONZE.CC_VENTAS_DEMO.STG_DEMO/ventas_demo.csv
    FILE_FORMAT = (FORMAT_NAME = 'COFFEE_BRONZE.LANDING.FF_CSV')
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (_FILE_NAME = METADATA$FILENAME, _FILE_ROW = METADATA$FILE_ROW_NUMBER, _LOADED_TS = METADATA$START_SCAN_TIME)
    FORCE = TRUE;

  -- 2. Silver y Gold en orden de dependencias: STG -> DIM -> FCT -> AGG
  ALTER DYNAMIC TABLE COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS REFRESH;
  CREATE OR REPLACE TABLE COFFEE_SILVER.CC_VENTAS_DEMO.DIM_PRODUCT
    COMMENT = 'Dimensión producto | owner: Claude Code | fuente: VENTAS_DEMO'
  AS SELECT HASH(PRODUCT_ID) AS PRODUCT_SK, PRODUCT_ID, MAX(PRODUCT_NAME) AS PRODUCT_NAME, MAX(CATEGORY_NAME) AS CATEGORY_NAME
     FROM COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS WHERE PRODUCT_ID IS NOT NULL GROUP BY PRODUCT_ID;
  CREATE OR REPLACE TABLE COFFEE_SILVER.CC_VENTAS_DEMO.DIM_STORE
    COMMENT = 'Dimensión tienda | owner: Claude Code | fuente: VENTAS_DEMO'
  AS SELECT HASH(STORE_ID) AS STORE_SK, STORE_ID, MAX(STORE_NAME) AS STORE_NAME, MAX(CITY_NAME) AS CITY_NAME
     FROM COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS WHERE STORE_ID IS NOT NULL GROUP BY STORE_ID;
  CREATE OR REPLACE TABLE COFFEE_SILVER.CC_VENTAS_DEMO.FCT_SALES
    COMMENT = 'Hecho ventas, grano: línea de orden (ORDER_ID, PRODUCT_SK) | owner: Claude Code | fuente: VENTAS_DEMO'
  AS SELECT O.ORDER_ID, O.ORDER_DATE, P.PRODUCT_SK, S.STORE_SK, O.PAYMENT_METHOD_NAME, O.ITEM_QTY, O.UNIT_PRICE_AMT, O.TOTAL_AMT
     FROM COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS O
     JOIN COFFEE_SILVER.CC_VENTAS_DEMO.DIM_PRODUCT P ON P.PRODUCT_ID = O.PRODUCT_ID
     JOIN COFFEE_SILVER.CC_VENTAS_DEMO.DIM_STORE S ON S.STORE_ID = O.STORE_ID
     WHERE O.ORDER_DATE IS NOT NULL AND O.TOTAL_AMT IS NOT NULL;
  ALTER DYNAMIC TABLE COFFEE_GOLD.CC_VENTAS_DEMO.AGG_SALES_DAILY_STORE REFRESH;

  -- 3. Conteos por objeto
  SELECT COUNT(*) INTO :n FROM COFFEE_BRONZE.CC_VENTAS_DEMO.RAW_ORDERS;
  resumen := resumen || 'RAW_ORDERS: ' || n || CHR(10);
  SELECT COUNT(*) INTO :n FROM COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS;
  resumen := resumen || 'STG_ORDERS: ' || n || CHR(10);
  SELECT COUNT(*) INTO :n FROM COFFEE_SILVER.CC_VENTAS_DEMO.DIM_PRODUCT;
  resumen := resumen || 'DIM_PRODUCT: ' || n || CHR(10);
  SELECT COUNT(*) INTO :n FROM COFFEE_SILVER.CC_VENTAS_DEMO.DIM_STORE;
  resumen := resumen || 'DIM_STORE: ' || n || CHR(10);
  SELECT COUNT(*) INTO :n FROM COFFEE_SILVER.CC_VENTAS_DEMO.FCT_SALES;
  resumen := resumen || 'FCT_SALES: ' || n || CHR(10);
  SELECT COUNT(*) INTO :n FROM COFFEE_GOLD.CC_VENTAS_DEMO.AGG_SALES_DAILY_STORE;
  resumen := resumen || 'AGG_SALES_DAILY_STORE: ' || n || CHR(10);
  RETURN resumen;
END;
$$;

-- Uso: CALL COFFEE_GOLD.CC_VENTAS_DEMO.SP_REFRESH_VENTAS_DEMO();
