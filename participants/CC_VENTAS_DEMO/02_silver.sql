-- Silver de VENTAS_DEMO | INI = CC
USE ROLE COFFEE_LAB_PARTICIPANT;
USE WAREHOUSE COMPUTE_WH;

CREATE SCHEMA IF NOT EXISTS COFFEE_SILVER.CC_VENTAS_DEMO
  COMMENT = 'Silver de VENTAS_DEMO | owner: Claude Code | fuente: VENTAS_DEMO';

CREATE OR REPLACE DYNAMIC TABLE COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS
  TARGET_LAG = '1 day' WAREHOUSE = COMPUTE_WH
  COMMENT = 'Líneas de orden tipadas y deduplicadas | owner: Claude Code | fuente: VENTAS_DEMO'
AS
SELECT
  TRY_TO_NUMBER(ORDER_ID)                    AS ORDER_ID,
  TRY_TO_DATE(ORDER_DATE)                    AS ORDER_DATE,
  UPPER(NULLIF(TRIM(STORE_ID), ''))          AS STORE_ID,
  INITCAP(NULLIF(TRIM(STORE_NAME), ''))      AS STORE_NAME,
  INITCAP(NULLIF(TRIM(CITY), ''))            AS CITY_NAME,
  UPPER(NULLIF(TRIM(PRODUCT_ID), ''))        AS PRODUCT_ID,
  INITCAP(NULLIF(TRIM(PRODUCT_NAME), ''))    AS PRODUCT_NAME,
  INITCAP(NULLIF(TRIM(CATEGORY), ''))        AS CATEGORY_NAME,
  TRY_TO_NUMBER(QUANTITY)                    AS ITEM_QTY,
  TRY_TO_DECIMAL(UNIT_PRICE, 12, 2)          AS UNIT_PRICE_AMT,
  TRY_TO_DECIMAL(DISCOUNT_PCT, 5, 2)         AS DISCOUNT_PCT,
  INITCAP(NULLIF(TRIM(PAYMENT_METHOD), ''))  AS PAYMENT_METHOD_NAME,
  ITEM_QTY * UNIT_PRICE_AMT * (1 - COALESCE(DISCOUNT_PCT, 0) / 100) AS TOTAL_AMT,
  _LOADED_TS,
  CURRENT_TIMESTAMP()                        AS _UPDATED_TS
FROM COFFEE_BRONZE.CC_VENTAS_DEMO.RAW_ORDERS
QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID, PRODUCT_ID ORDER BY _LOADED_TS DESC) = 1;

CREATE OR REPLACE TABLE COFFEE_SILVER.CC_VENTAS_DEMO.DIM_PRODUCT
  COMMENT = 'Dimensión producto | owner: Claude Code | fuente: VENTAS_DEMO'
AS
SELECT HASH(PRODUCT_ID) AS PRODUCT_SK, PRODUCT_ID, MAX(PRODUCT_NAME) AS PRODUCT_NAME, MAX(CATEGORY_NAME) AS CATEGORY_NAME
FROM COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS WHERE PRODUCT_ID IS NOT NULL GROUP BY PRODUCT_ID;

CREATE OR REPLACE TABLE COFFEE_SILVER.CC_VENTAS_DEMO.DIM_STORE
  COMMENT = 'Dimensión tienda | owner: Claude Code | fuente: VENTAS_DEMO'
AS
SELECT HASH(STORE_ID) AS STORE_SK, STORE_ID, MAX(STORE_NAME) AS STORE_NAME, MAX(CITY_NAME) AS CITY_NAME
FROM COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS WHERE STORE_ID IS NOT NULL GROUP BY STORE_ID;

CREATE OR REPLACE TABLE COFFEE_SILVER.CC_VENTAS_DEMO.DIM_DATE
  COMMENT = 'Dimensión fecha | owner: Claude Code | fuente: VENTAS_DEMO'
AS
WITH R AS (SELECT MIN(ORDER_DATE) AS D0, MAX(ORDER_DATE) AS D1 FROM COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS)
SELECT * FROM (
  SELECT DATEADD(DAY, SEQ4(), R.D0) AS DATE_KEY, YEAR(DATE_KEY) AS YEAR_NUM, MONTH(DATE_KEY) AS MONTH_NUM,
       MONTHNAME(DATE_KEY) AS MONTH_NAME, DAYNAME(DATE_KEY) AS WEEKDAY_NAME, DAYOFWEEKISO(DATE_KEY) IN (6,7) AS IS_WEEKEND
  FROM R, TABLE(GENERATOR(ROWCOUNT => 3660))
) WHERE DATE_KEY <= (SELECT D1 FROM R);

CREATE OR REPLACE TABLE COFFEE_SILVER.CC_VENTAS_DEMO.FCT_SALES
  COMMENT = 'Hecho ventas, grano: línea de orden (ORDER_ID, PRODUCT_SK) | owner: Claude Code | fuente: VENTAS_DEMO'
AS
SELECT O.ORDER_ID, O.ORDER_DATE, P.PRODUCT_SK, S.STORE_SK, O.PAYMENT_METHOD_NAME, O.ITEM_QTY, O.UNIT_PRICE_AMT, O.TOTAL_AMT
FROM COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS O
JOIN COFFEE_SILVER.CC_VENTAS_DEMO.DIM_PRODUCT P ON P.PRODUCT_ID = O.PRODUCT_ID
JOIN COFFEE_SILVER.CC_VENTAS_DEMO.DIM_STORE S ON S.STORE_ID = O.STORE_ID
WHERE O.ORDER_DATE IS NOT NULL AND O.TOTAL_AMT IS NOT NULL;

-- Validaciones
SELECT 'STG filas con fecha inválida' AS CHECK_NAME, COUNT_IF(ORDER_DATE IS NULL) AS VALOR FROM COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS
UNION ALL SELECT 'STG filas sin precio', COUNT_IF(UNIT_PRICE_AMT IS NULL) FROM COFFEE_SILVER.CC_VENTAS_DEMO.STG_ORDERS
UNION ALL SELECT 'DIM_PRODUCT unicidad (debe ser 0)', COUNT(*) - COUNT(DISTINCT PRODUCT_ID) FROM COFFEE_SILVER.CC_VENTAS_DEMO.DIM_PRODUCT
UNION ALL SELECT 'FCT sin tienda o producto (debe ser 0)', COUNT_IF(PRODUCT_SK IS NULL OR STORE_SK IS NULL) FROM COFFEE_SILVER.CC_VENTAS_DEMO.FCT_SALES
UNION ALL SELECT 'FCT filas', COUNT(*) FROM COFFEE_SILVER.CC_VENTAS_DEMO.FCT_SALES;
